/** Runs on the raw user message, before any agent/LLM work. */
export function preCheck(message: string, lang: Lang): PreCheckResult {
  // E-06: the detector is deterministic code, but it must never fail silently.
  // On unexpected error, fail CLOSED (escalate) and record the fault.
  let emergency: EmergencyHit | null;
  try {
    emergency = detectEmergency(message);
  } catch (err) {
    return {
      escalate: true,
      emergency: null,
      text: lang === 'ar' ? ESCALATION_AR : ESCALATION_EN,
      checks: [
        {
          name: 'emergency_detection',
          passed: false,
          detail: `detector_error: ${String(err).slice(0, 120)} — failed closed`,
        },
      ],
    };
  }
  if (emergency) {
    return {
      escalate: true,
      emergency,
      text: lang === 'ar' ? ESCALATION_AR : ESCALATION_EN,
      checks: [
        {
          name: 'emergency_detection',
          passed: false,
          detail: `hit:${emergency.category} (keyword "${emergency.matched}")`,
        },
      ],
    };
  }
  return {
    escalate: false,
    emergency: null,
    text: '',
    checks: [{ name: 'emergency_detection', passed: true }],
  };
}

