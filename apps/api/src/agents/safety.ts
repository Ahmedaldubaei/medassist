/**
 * Clinical Safety Gate — deterministic, runs BEFORE and AFTER the LLM.
 * The LLM is never trusted with safety decisions (MediGenius
 * safety_router + dosage_grounding pattern, reimplemented in
 * TypeScript with Arabic localization).
 *
 * - preCheck(message): emergency → immediate escalation, no LLM call.
 * - postCheck(draft, chunks): dosage grounding, citation verification,
 *   confidence scoring, mandatory disclaimer.
 */
import type { RetrievalResult } from '../rag/retrieve.js';
import { detectEmergency, type EmergencyHit, type Lang } from './router.js';

/** Safety policy version (policy §11 traceability). */
export const POLICY_VERSION = '2.0-draft';

/**
 * Verdict taxonomy (policy §9.3).
 * - PASS: technical checks passed (NOT a clinical approval).
 * - FLAG: non-critical issue corrected/clarified, answer re-checked.
 * - CLARIFY: reserved — cannot safely answer before more information
 *   (no deterministic trigger implemented yet; conversational agents handle
 *   clarification today).
 * - ESCALATE: emergency / needs immediate human-clinical escalation.
 * - BLOCK: unsafe content/action blocked.
 * - SAFE_FALLBACK: critical component failed; limited safe response shown.
 */
export type SafetyVerdict = 'PASS' | 'FLAG' | 'CLARIFY' | 'ESCALATE' | 'BLOCK' | 'SAFE_FALLBACK';

/** Runtime list of the verdict taxonomy (for tests and logging). */
export const SAFETY_VERDICTS: readonly SafetyVerdict[] = [
  'PASS',
  'FLAG',
  'CLARIFY',
  'ESCALATE',
  'BLOCK',
  'SAFE_FALLBACK',
];

export interface Citation {
  n: number;
  title: string;
  source: string;
  guidelineYear: number | null;
  url: string | null;
  license: string;
}

export interface SafetyCheck {
  name: string;
  passed: boolean;
  detail?: string;
}

export interface PreCheckResult {
  escalate: boolean;
  emergency: EmergencyHit | null;
  /** Ready-to-send escalation text (already includes guidance). */
  text: string;
  checks: SafetyCheck[];
}

