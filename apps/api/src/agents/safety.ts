/**
 * Dosage-text normalization (policy §7, tests D-01..D-12).
 * Applied BEFORE extraction, to both drafts and chunk text:
 * - Arabic-Indic digits ٠-٩ → 0-9
 * - Arabic decimal separator ٫ (U+066B) → .
 * - Arabic thousands separator ٬ (U+066C) → removed
 */
const AR_INDIC_DIGITS = '٠١٢٣٤٥٦٧٨٩';

export function normalizeDosageText(text: string): string {
  return text
    .replace(/[٠-٩]/g, (d) => String(AR_INDIC_DIGITS.indexOf(d)))
    .replace(/٫/g, '.')
    .replace(/٬/g, '');
}

/**
 * Dosage mention: number (optionally a range) + unit, EN or AR.
 * e.g. "2.5 mg/kg", "2,5 mg" (comma decimal), "1-2 mg", "50 mcg",
 * "5 ملغ", "٠٫٥ ملغ" (Arabic-Indic, normalized first), "وحدة/كغ".
 * Note: \b is ASCII-only, so the trailing boundary uses a
 * Unicode-aware lookahead instead (works after Arabic script).
 */
const DOSAGE_RE =
  /(\d+(?:[.,]\d+)?)(?:\s*[-–]\s*(\d+(?:[.,]\d+)?))?\s*(mg|mcg|µg|μg|g|ml|l|units?|iu|ملغ|مكغ|ميكروغرام|ميكروجرام|غرام|جم|مل|وحدة|وحدات|كغ|كجم|kg)(?![\p{L}\p{N}])/giu;

/** Unit normalization for grounding comparison (EN ↔ AR). */
const UNIT_GROUPS: string[][] = [
  ['mg', 'ملغ'],
  ['mcg', 'µg', 'μg', 'مكغ', 'ميكروغرام', 'ميكروجرام'],
  ['g', 'غرام', 'جم'],
  ['ml', 'مل'],
  ['l'],
  ['unit', 'units', 'iu', 'وحدة', 'وحدات'],
  ['kg', 'كغ', 'كجم'],
];

function unitGroup(unit: string): string[] {
  const u = unit.toLowerCase();
  return UNIT_GROUPS.find((g) => g.includes(u)) ?? [u];
}

export interface DosageMention {
  raw: string;
  numbers: string[];
  unit: string;
  index: number;
}

/** Normalizes a captured number: comma decimal → dot ("2,5" → "2.5"). */
function normNumber(n: string): string {
  return n.replace(',', '.');
}

/**
 * Extracts all dosage mentions from a draft answer.
 * Input is normalized first (Arabic-Indic digits, decimal separators),
 * so "٠٫٥ ملغ" and "2,5 mg" are detected as 0.5 / 2.5.
 */
export function extractDosages(text: string): DosageMention[] {
  const src = normalizeDosageText(text);
  const out: DosageMention[] = [];
  DOSAGE_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = DOSAGE_RE.exec(src)) !== null) {
    const numbers = [normNumber(m[1]!), ...(m[2] ? [normNumber(m[2]!)] : [])];
    out.push({ raw: m[0], numbers, unit: m[3]!.toLowerCase(), index: m.index });
  }
  return out;
}

/**
 * Administration-route groups (policy §7.4: dose validity depends on route).
 * Used by isDosageGrounded: a draft dose stated for a route is grounded only
 * by a chunk dose for the SAME route group. Drafts with no route stated keep
 * the permissive number+unit behavior.
 */
const ROUTE_GROUPS: string[][] = [
  ['iv', 'intravenous', 'intravenously', 'i.v.', 'وريدي', 'وريديا', 'بالوريد', 'حقن وريدي'],
  ['im', 'intramuscular', 'intramuscularly', 'i.m.', 'عضلي', 'بالعضل', 'حقن عضلي'],
  ['sc', 'subcutaneous', 'subcutaneously', 's.c.', 'تحت الجلد'],
  ['po', 'oral', 'orally', 'بالفم', 'فموي', 'عن طريق الفم'],
  ['inhalation', 'inhaled', 'استنشاق', 'استنشاقي'],
  ['epidural', 'فوق الجافية', 'فوق الجافيه'],
  ['spinal', 'intrathecal', 'نخاعي', 'داخل القراب'],
  ['topical', 'موضعي', 'موضعيا'],
];

/** Returns the route-group indexes mentioned in a sentence (empty = none stated). */
function routesIn(sentence: string): number[] {
  const low = normalizeDosageText(sentence.toLowerCase());
  const out: number[] = [];
  ROUTE_GROUPS.forEach((group, i) => {
    const hit = group.some((r) => {
      const rl = r.toLowerCase();
      // Short Latin codes (iv/im/sc/po/…) need word boundaries — otherwise
      // "iv" matches inside "give" and "im" inside "him".
      if (/^[a-z.]{1,4}$/.test(rl)) {
        const esc = rl.replace(/\./g, '\\.');
        return new RegExp(`(?<![\\p{L}\\p{N}])${esc}(?![\\p{L}\\p{N}])`, 'u').test(low);
      }
      return low.includes(rl);
    });
    if (hit) out.push(i);
  });
  return out;
}

/**
 * Prompt-injection screen for retrieved chunks (policy §12, tests S-01/S-08).
 * Retrieved content is untrusted data: a chunk that tries to override system
 * instructions or exfiltrate secrets must not be allowed to ground doses.
 */
const INJECTION_RE =
  /تجاهل (التعليمات|تعليمات|ما سبق|كل ما سبق)|ignore (all |any |the )?(previous|prior|above) instructions|اكشف (مفتاح|كلمة|السر|api)|reveal (the )?(api key|secret|password)|system prompt|تعليمات النظام الجديدة/i;

export function isChunkCompromised(text: string): boolean {
  INJECTION_RE.lastIndex = 0;
  return INJECTION_RE.test(text);
}

/**
 * A dosage is grounded only if some NON-COMPROMISED retrieved chunk contains
 * a dosage mention with the same number AND a unit from the same unit group,
 * in a sentence whose administration route is compatible with the draft's
 * stated route (policy §7.4, test D-02).
 * (Number and unit must co-occur as a real mention — checking them
 * independently anywhere in the chunk causes false grounding, e.g.
 * "100 percent oxygen" + "2.5 mg" would wrongly ground "100 mg".)
 */
export function isDosageGrounded(
  d: DosageMention,
  chunks: RetrievalResult[],
  draftSentence?: string,
): boolean {
  const units = unitGroup(d.unit);
  const draftRoutes = draftSentence ? routesIn(draftSentence) : [];
  return chunks.some((c) => {
    const text = `${c.textEn ?? ''} ${c.textAr ?? ''}`;
    // Quarantine: a compromised chunk can never ground a dose (S-01/S-08).
    if (isChunkCompromised(text)) return false;
    return splitSentences(text).some((sentence) => {
      const chunkRoutes = routesIn(sentence);
      // Route compatibility (D-02): if the draft states a route, the chunk
      // sentence must share a route group.
      if (draftRoutes.length > 0 && !draftRoutes.some((r) => chunkRoutes.includes(r))) {
        return false;
      }
      return extractDosages(sentence).some(
        (cd) =>
          cd.numbers.some((n) => d.numbers.includes(n)) &&
          unitGroup(cd.unit).some((u) => units.includes(u)),
      );
    });
  });
}

// Accepts both [n] (prompt format) and 【n†Lx-Ly】/【n】 (what LLMs often emit).
const CITATION_RE = /(?:\[|【)(\d+)(?:\]|(?:†[^】]*)?】)/g;

export interface PostCheckInput {
  draft: string;
  chunks: RetrievalResult[];
  lang: Lang;
}

export interface PostCheckResult {
  verdict: SafetyVerdict;
  /** Sanitized answer text (citations validated, ungrounded doses stripped). */
  text: string;
  citations: Citation[];
  confidence: number;
  checks: SafetyCheck[];
  strippedDosages: string[];
}

/**
 * Splits text into sentences (AR/EN aware) for surgical removal of
 * ungrounded dosage sentences.
 */
function splitSentences(text: string): string[] {
  return text.split(/(?<=[.!?؟。\n])\s+/).filter((s) => s.trim().length > 0);
}

/**
 * Returns the first sentence whose normalized form contains the given
 * (normalized) dosage mention text. Used to give isDosageGrounded the draft
 * sentence as route context — matched by text rather than index because
 * dosage normalization can shift character offsets.
 */
function sentenceWithMention(text: string, rawMention: string): string | undefined {
  return splitSentences(text).find((s) => normalizeDosageText(s).includes(rawMention));
}

/**
 * Secret-pattern redaction (policy §11: never log/return secrets).
 * If a draft quotes something that looks like an API key/secret
 * (e.g. from a compromised chunk), it is masked before display.
 */
const SECRET_RE = /\b(sk-[A-Za-z0-9-]{20,})\b|\b(api[_-]?key\s*[:=]\s*['"]?\S+)/gi;

export function redactSecrets(text: string): string {
  SECRET_RE.lastIndex = 0;
  return text.replace(SECRET_RE, '[REDACTED]');
}

export function postCheck({ draft, chunks, lang }: PostCheckInput): PostCheckResult {
  const checks: SafetyCheck[] = [];
  let text = redactSecrets(draft);
  const strippedDosages: string[] = [];
  let verdict: SafetyVerdict = 'PASS';

  // 0) Injection screen (policy §12, tests S-01/S-08): quarantine compromised
  //    retrieved chunks so they can never ground doses (see isDosageGrounded).
  const compromised = chunks.filter((c) =>
    isChunkCompromised(`${c.textEn ?? ''} ${c.textAr ?? ''}`),
  );
  checks.push({
    name: 'injection_screen',
    passed: compromised.length === 0,
    detail:
      compromised.length === 0
        ? 'no injection patterns in retrieved chunks'
        : `${compromised.length} chunk(s) quarantined (injection pattern)`,
  });

  // 1) Citation verification: every [n] must map to a retrieved chunk.
  const cited = new Set<number>();
  CITATION_RE.lastIndex = 0;
  let cm: RegExpExecArray | null;
  let fabricated = 0;
  while ((cm = CITATION_RE.exec(draft)) !== null) {
    const n = Number(cm[1]);
    if (n >= 1 && n <= chunks.length) cited.add(n);
    else fabricated++;
  }
  if (fabricated > 0) {
    // Remove fabricated markers rather than showing fake references.
    text = text.replace(/(?:\[|【)(\d+)(?:\]|(?:†[^】]*)?】)/g, (full, n: string) => {
      const idx = Number(n);
      return idx >= 1 && idx <= chunks.length ? full : '';
    });
    verdict = 'FLAG';
    checks.push({
      name: 'citation_verification',
      passed: false,
      detail: `${fabricated} fabricated citation marker(s) removed`,
    });
  } else {
    checks.push({ name: 'citation_verification', passed: true });
  }

  // 2) Dosage grounding (MediGenius dosage_grounding): strip any dosage
  //    sentence whose dose is not supported by the retrieved chunks.
  //    Route-aware (policy §7.4, test D-02): the sentence containing the
  //    draft dose is passed as context so a different-route chunk cannot
  //    ground it.
  const dosages = extractDosages(text);
  const ungrounded = dosages.filter((d) => {
    const sentence = sentenceWithMention(text, d.raw);
    return !isDosageGrounded(d, chunks, sentence);
  });
  if (ungrounded.length > 0) {
    // Drop every sentence containing at least one ungrounded dosage.
    const sentences = splitSentences(text);
    const kept = sentences.filter((s) => {
      const bad = extractDosages(s).some((d) => !isDosageGrounded(d, chunks, s));
      if (bad) strippedDosages.push(s.trim().slice(0, 120));
      return !bad;
    });
    text = kept.join(' ');
    verdict = 'FLAG';
    checks.push({
      name: 'dosage_grounding',
      passed: false,
      detail: `${ungrounded.length} ungrounded dosage mention(s) stripped: ${ungrounded.map((u) => u.raw).join(', ')}`,
    });
    if (text.trim().length < 20) {
      // The answer was dose-centric with no grounded content left: block it.
      return {
        verdict: 'BLOCK',
        text:
          lang === 'ar'
            ? 'تم حجب هذه الإجابة: تضمنت جرعات دوائية غير مدعومة بالمصادر الموثقة المسترجعة. أعد صياغة السؤال أو راجع المصدر الأصلي.'
            : 'This answer was blocked: it contained drug doses not supported by the retrieved verified sources. Rephrase the question or consult the original source.',
        citations: [],
        confidence: 0,
        checks: [...checks, { name: 'dose_centric_block', passed: false }],
        strippedDosages,
      };
    }
  } else {
    checks.push({
      name: 'dosage_grounding',
      passed: true,
      detail: dosages.length === 0 ? 'no dosage mentions' : `${dosages.length} dosage(s) grounded`,
    });
  }

  // 3) Build the verified citation list (only chunks actually cited).
  const citations: Citation[] = [...cited]
    .sort((a, b) => a - b)
    .map((n) => {
      const c = chunks[n - 1]!;
      return {
        n,
        title: c.title,
        source: c.source,
        guidelineYear: c.guidelineYear,
        url: c.url,
        license: c.license,
      };
    });

  // 4) Confidence: deterministic, based on retrieval evidence.
  const citedCount = cited.size;
  const avgScore =
    chunks.length > 0 ? chunks.reduce((a, c) => a + c.score, 0) / chunks.length : 0;
  const confidence = Math.min(
    0.95,
    Math.max(0.1, 0.35 + 0.15 * Math.min(citedCount, 3) + Math.min(avgScore * 2, 0.2)),
  );

  return { verdict, text: text.trim(), citations, confidence, checks, strippedDosages };
}
